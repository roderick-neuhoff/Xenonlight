"""Writes xdk/src/deblock_tables.h: H.264's deblocking thresholds per QP (0..51),
taken from FFmpeg's libavcodec/h264_loopfilter.c, for the GPU deblocking shader.

    python xdk/scripts/gen_deblock_tables.py
"""
import os
import re

XDK = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(XDK, "deps", "XBMC-360", "libraries", "ffmpeg", "libavcodec", "h264_loopfilter.c")


def table(text, name):
    body = re.search(name + r"\[[^\]]*\](?:\[4\])?\s*=\s*\{(.*?)\};", text, re.S).group(1)
    return [int(v) for v in re.findall(r"-?\d+", body)]


text = open(SRC, encoding="utf-8").read()
alpha = table(text, "alpha_table")[52:104]   # FFmpeg indexes these by qp + 52
beta = table(text, "beta_table")[52:104]
tc0 = table(text, "tc0_table")
tc0 = [tc0[(52 + qp) * 4: (52 + qp) * 4 + 4] for qp in range(52)]   # [bS 0..3]

out = os.path.join(XDK, "src", "deblock_tables.h")
with open(out, "w", newline="\n") as f:
    f.write("// Generated by xdk/scripts/gen_deblock_tables.py from FFmpeg's h264_loopfilter.c.\n")
    f.write("// H.264 deblocking thresholds per QP: alpha, beta, tc0 for bS 1 and 2.\n#pragma once\n\n")
    f.write("static const unsigned char deblock_lut[52][4] = {\n")
    for qp in range(52):
        f.write(f"    {{ {alpha[qp]:3}, {beta[qp]:2}, {tc0[qp][1]:2}, {tc0[qp][2]:2} }},   // QP {qp}\n")
    f.write("};\n")
print("wrote", out)
